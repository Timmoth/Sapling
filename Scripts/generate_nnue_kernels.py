#!/usr/bin/env python3
"""Deterministically generate NNUE kernels; --check verifies the checked-in artifact."""
from pathlib import Path
import sys

# All external offsets/pointers count shorts. Only the x86 body reinterprets vectors.
ops = [
 ('SimdResetAccumulators', ['whiteAcc','blackAcc'], 'whiteAcc[i] = blackAcc[i] = biases[i]'),
 ('SimdResetAccumulator', ['acc'], 'acc[i] = biases[i]'),
 ('SimdCopy', ['dest','src'], 'dest[i] = src[i]'),
 ('Sub', ['source','dest','sub'], 'dest[i] = source[i] - sub[i]'),
 ('Add', ['source','dest','add'], 'dest[i] = source[i] + add[i]'),
 ('AddWeights', ['accuPtr','featurePtr'], 'accuPtr[i] = accuPtr[i] + featurePtr[i]'),
 ('SubAdd', ['source','dest','sub1','add1'], 'dest[i] = source[i] - sub1[i] + add1[i]'),
 ('SubSubAdd', ['source','dest','sub1','sub2','add1'], 'dest[i] = source[i] - sub1[i] + add1[i] - sub2[i]'),
 ('SubSubAddAdd', ['source','dest','sub1','sub2','add1','add2'], 'dest[i] = source[i] - sub1[i] + add1[i] - sub2[i] + add2[i]'),
]
lines=['// <auto-generated> Scripts/generate_nnue_kernels.py; do not edit manually. </auto-generated>',
 'using System.Runtime.CompilerServices;', 'using System.Runtime.Intrinsics;',
 'using Sapling.Engine.Evaluation;', '', 'namespace Sapling.Engine.Search;', '',
 'public unsafe partial class Searcher', '{']
for name,args,expr in ops:
 lines += ['    [MethodImpl(MethodImplOptions.AggressiveInlining)]',
 f'    public static void {name}('+', '.join('short* '+a+'Data' for a in args)+')', '    {']
 sources=args+(['biases'] if 'biases' in expr else [])
 if 'biases' in sources: lines += ['        var biasesData = NnueWeights.FeatureBiases;']
 # Scalar and portable Vector128 are complete kernels, never dispatched per lane.
 # Vector128 (ARM64/portable) is unrolled 4 vectors per iteration: the 128-iteration
 # loop form leaves loop overhead and no ILP across iterations on ARM64.
 lines += ['        if (!EngineCapabilities.UseX86Nnue)', '        {',
  '            if (EngineCapabilities.UseVector128Nnue)', '            {',
  '                for (var i = 0; i < NnueWeights.Layer1Size; i += 4 * Vector128<short>.Count)', '                {']
 lhs,rhs=expr.rsplit(' = ',1)
 for u in range(4):
  off='' if u==0 else f' + {u} * Vector128<short>.Count'
  v=rhs
  for a in sources:v=v.replace(a+'[i]',f'Vector128.Load({a}Data + i{off})')
  lines += [f'                    var value{u} = {v};']
  for d in lhs.split(' = '): lines += [f'                    value{u}.Store({d.split("[")[0]}Data + i{off});']
 lines += ['                }','            }','            else','            {',
  '                for (var i = 0; i < NnueWeights.Layer1Size; i++)','                {']
 scalar=expr
 for a in sources:scalar=scalar.replace(a+'[i]',a+'Data[i]')
 l,r=scalar.rsplit(' = ',1)
 lines += [f'                    {l} = unchecked((short)({r}));','                }','            }','            return;','        }']
 for a in sources:lines += [f'        var {a} = (VectorShort*){a}Data;']
 for i in range(64):
  if i==32:lines+=['#if !AVX512']
  lines += ['        '+expr.replace('[i]',f'[{i}]')+';']
 lines += ['#endif','    }','']
lines += ['    [MethodImpl(MethodImplOptions.AggressiveInlining)]',
 '    private static int ForwardCReLU(short* usData, short* themData, int bucket)', '    {',
 '        var weights = NnueWeights.OutputWeights + bucket * NnueWeights.Layer1Size * 2;',
 '        var otherWeights = weights + NnueWeights.Layer1Size;',
 '        if (!EngineCapabilities.UseX86Nnue)', '        {',
  '            if (EngineCapabilities.UseVector128Nnue)', '            {',
  '                var sum0 = Vector128<int>.Zero;', '                var sum1 = Vector128<int>.Zero;',
  '                var sum2 = Vector128<int>.Zero;', '                var sum3 = Vector128<int>.Zero;',
  '                var floor128 = Vector128<short>.Zero;',
  '                var ceil128 = Vector128.Create((short)255);',
  '                for (var i = 0; i < NnueWeights.Layer1Size; i += 4 * Vector128<short>.Count)', '                {']
for u in range(4):
 off='' if u==0 else f' + {u} * Vector128<short>.Count'
 lines += [f'                    var us{u} = Vector128.Widen(Vector128.Clamp(Vector128.Load(usData + i{off}), floor128, ceil128));',
  f'                    var them{u} = Vector128.Widen(Vector128.Clamp(Vector128.Load(themData + i{off}), floor128, ceil128));',
  f'                    var w{u} = Vector128.Widen(Vector128.Load(weights + i{off}));',
  f'                    var other{u} = Vector128.Widen(Vector128.Load(otherWeights + i{off}));',
  f'                    sum{u} += us{u}.Lower * w{u}.Lower + us{u}.Upper * w{u}.Upper + them{u}.Lower * other{u}.Lower + them{u}.Upper * other{u}.Upper;']
lines += ['                }', '                return Vector128.Sum(sum0 + sum1 + sum2 + sum3);', '            }',
 '            var scalar = 0;', '            for (var i = 0; i < NnueWeights.Layer1Size; i++)',
 '                scalar = unchecked(scalar + Math.Clamp((int)usData[i], 0, 255) * weights[i]',
 '                    + Math.Clamp((int)themData[i], 0, 255) * otherWeights[i]);',
 '            return scalar;', '        }',
 '        var usAcc = (VectorShort*)usData;', '        var themAcc = (VectorShort*)themData;',
 '        var wPtr = (VectorShort*)weights;', '        var otherPtr = (VectorShort*)otherWeights;',
 '        var ceil = VectorType.Create((short)255);', '        var floor = VectorShort.Zero;',
 '        var sum = VectorInt.Zero;']
for i in range(64):
 if i==32:lines+=['#if !AVX512']
 lines += [f'        sum += AvxIntrinsics.MultiplyAddAdjacent(AvxIntrinsics.Max(AvxIntrinsics.Min(usAcc[{i}], ceil), floor), wPtr[{i}])',
 f'             + AvxIntrinsics.MultiplyAddAdjacent(AvxIntrinsics.Max(AvxIntrinsics.Min(themAcc[{i}], ceil), floor), otherPtr[{i}]);']
lines += ['#endif','        return VectorType.Sum(sum);','    }','}']
output='\n'.join(lines)+'\n'
target=Path(__file__).resolve().parent.parent/'src/Sapling.Engine/Evaluation/Unrolled.cs'
if '--check' in sys.argv:
 if target.read_text()!=output: raise SystemExit('Generated NNUE kernels are stale')
else: target.write_text(output)
